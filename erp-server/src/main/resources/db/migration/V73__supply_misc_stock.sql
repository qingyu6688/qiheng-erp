CREATE TABLE stock_misc_doc (
    id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    document_no VARCHAR(64) NOT NULL,
    direction VARCHAR(3) NOT NULL,
    purpose VARCHAR(64) NOT NULL,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    partner_id BIGINT UNSIGNED NULL,
    income_expense_item_id BIGINT UNSIGNED NOT NULL,
    business_date DATE NOT NULL,
    expected_return_date DATE NULL,
    original_loan_id BIGINT UNSIGNED NULL,
    owner_user_id BIGINT UNSIGNED NOT NULL,
    owner_department_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
    status VARCHAR(10) NOT NULL DEFAULT 'draft',
    approved_by BIGINT UNSIGNED NULL,
    approved_at DATETIME(3) NULL,
    posted_by BIGINT UNSIGNED NULL,
    posted_at DATETIME(3) NULL,
    period_id BIGINT UNSIGNED NULL,
    remark VARCHAR(500) NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY(id),
    UNIQUE KEY uk_misc_scope(tenant_id,company_id,id),
    UNIQUE KEY uk_misc_no(tenant_id,company_id,document_no),
    KEY idx_misc_list(tenant_id,company_id,direction,status,warehouse_id,id),
    KEY idx_misc_loan(tenant_id,company_id,original_loan_id,status,id),
    KEY idx_misc_due(tenant_id,company_id,direction,purpose,status,expected_return_date),
    CONSTRAINT fk_misc_wh FOREIGN KEY(tenant_id,company_id,warehouse_id) REFERENCES warehouse(tenant_id,company_id,id),
    CONSTRAINT fk_misc_party FOREIGN KEY(tenant_id,partner_id) REFERENCES business_partner(tenant_id,id),
    CONSTRAINT fk_misc_item FOREIGN KEY(tenant_id,income_expense_item_id) REFERENCES income_expense_item(tenant_id,id),
    CONSTRAINT fk_misc_loan FOREIGN KEY(tenant_id,company_id,original_loan_id) REFERENCES stock_misc_doc(tenant_id,company_id,id),
    CONSTRAINT fk_misc_period FOREIGN KEY(tenant_id,company_id,period_id) REFERENCES accounting_period(tenant_id,company_id,id),
    CONSTRAINT ck_misc_direction CHECK(direction IN('in','out')),
    CONSTRAINT ck_misc_status CHECK(status IN('draft','pending','approved','posted','reversed','voided')),
    CONSTRAINT ck_misc_approver CHECK(approved_by IS NULL OR approved_by<>created_by),
    CONSTRAINT ck_misc_posted CHECK((status IN('posted','reversed'))=(period_id IS NOT NULL AND posted_at IS NOT NULL)),
    CONSTRAINT ck_misc_relation CHECK(
        (purpose='loan' AND direction='out' AND expected_return_date>=business_date AND original_loan_id IS NULL AND partner_id IS NOT NULL)
        OR (purpose='loan_return' AND direction='in' AND expected_return_date IS NULL AND original_loan_id IS NOT NULL AND partner_id IS NOT NULL)
        OR (purpose NOT IN('loan','loan_return') AND expected_return_date IS NULL AND original_loan_id IS NULL))
);

CREATE TABLE stock_misc_line (
    id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    doc_id BIGINT UNSIGNED NOT NULL,
    line_no INT UNSIGNED NOT NULL,
    sku_id BIGINT UNSIGNED NOT NULL,
    unit_id BIGINT UNSIGNED NOT NULL,
    unit_rate DECIMAL(24,8) NOT NULL,
    qty DECIMAL(24,6) NOT NULL,
    base_qty DECIMAL(24,6) NOT NULL,
    input_unit_cost DECIMAL(24,8) NULL,
    zero_cost_reason VARCHAR(200) NULL,
    unit_cost DECIMAL(24,8) NULL,
    amount DECIMAL(24,2) NULL,
    batch_id BIGINT UNSIGNED NULL,
    location_key VARCHAR(64) NOT NULL DEFAULT '',
    stock_selection JSON NULL,
    original_loan_line_id BIGINT UNSIGNED NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY(id),
    UNIQUE KEY uk_misc_line_scope(tenant_id,company_id,id),
    UNIQUE KEY uk_misc_line_no(tenant_id,company_id,doc_id,line_no),
    KEY idx_misc_line_loan(tenant_id,company_id,original_loan_line_id,doc_id),
    CONSTRAINT fk_misc_line_doc FOREIGN KEY(tenant_id,company_id,doc_id) REFERENCES stock_misc_doc(tenant_id,company_id,id),
    CONSTRAINT fk_misc_line_sku FOREIGN KEY(tenant_id,sku_id) REFERENCES sku(tenant_id,id),
    CONSTRAINT fk_misc_line_unit FOREIGN KEY(tenant_id,unit_id) REFERENCES unit(tenant_id,id),
    CONSTRAINT fk_misc_line_batch FOREIGN KEY(tenant_id,company_id,batch_id) REFERENCES inv_batch(tenant_id,company_id,id),
    CONSTRAINT fk_misc_line_loan FOREIGN KEY(tenant_id,company_id,original_loan_line_id) REFERENCES stock_misc_line(tenant_id,company_id,id),
    CONSTRAINT ck_misc_line_qty CHECK(qty>0 AND base_qty>0 AND unit_rate>0),
    CONSTRAINT ck_misc_line_cost CHECK(input_unit_cost IS NULL OR input_unit_cost>0 OR (input_unit_cost=0 AND zero_cost_reason IS NOT NULL))
);
