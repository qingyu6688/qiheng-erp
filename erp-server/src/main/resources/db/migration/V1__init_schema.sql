-- ERP 首期业务表结构。
SET NAMES utf8mb4;

-- =====================================================================
-- 1. 组织与权限
-- =====================================================================

CREATE TABLE tenant (
  id          BIGINT UNSIGNED NOT NULL,
  code        VARCHAR(32)  NOT NULL COMMENT '租户编码',
  name        VARCHAR(100) NOT NULL COMMENT '租户名称',
  status      VARCHAR(16)  NOT NULL DEFAULT 'active' COMMENT 'active 启用 / disabled 停用',
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenant_code (code),
  CONSTRAINT ck_tenant_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='租户，数据隔离边界';

CREATE TABLE company (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  code        VARCHAR(16)  NOT NULL COMMENT '公司编码，出现在单号中（R8-08）',
  name        VARCHAR(100) NOT NULL,
  tax_no      VARCHAR(32)  NULL COMMENT '统一社会信用代码',
  address     VARCHAR(200) NULL COMMENT '打印单据抬头用',
  phone       VARCHAR(32)  NULL COMMENT '打印单据抬头用',
  status      VARCHAR(16)  NOT NULL DEFAULT 'active' COMMENT 'active 启用 / disabled 停用',
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_company_code (tenant_id, code),
  UNIQUE KEY uk_company_scope (tenant_id, id),
  CONSTRAINT fk_company_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
  CONSTRAINT ck_company_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='公司，业务主体';

CREATE TABLE company_policy (
  id                          BIGINT UNSIGNED NOT NULL,
  tenant_id                   BIGINT UNSIGNED NOT NULL,
  company_id                  BIGINT UNSIGNED NOT NULL,
  taxpayer_type               VARCHAR(16)  NOT NULL DEFAULT 'general' COMMENT 'general 一般纳税人 / small 小规模纳税人，决定采购入库成本取未税或含税（R6-04）',
  reservation_valid_days      SMALLINT UNSIGNED NOT NULL DEFAULT 30 COMMENT '预留有效天数（R1-05）',
  reservation_grace_days      SMALLINT UNSIGNED NOT NULL DEFAULT 7  COMMENT '约定交货日之后的预留宽限天数（R1-05）',
  over_receipt_pct            DECIMAL(5,2) NOT NULL DEFAULT 0.00 COMMENT '采购超收容差百分比，审批时写入订单行（R4-03）',
  separate_order_approver     TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '订单审批人须不同于制单人（业务规则第 12 节）',
  separate_receipt_confirmer  TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '收付款确认人须不同于登记人（业务规则第 12 节）',
  version                     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by                  BIGINT UNSIGNED NULL,
  created_at                  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by                  BIGINT UNSIGNED NULL,
  updated_at                  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_company_policy (tenant_id, company_id),
  CONSTRAINT fk_company_policy_company FOREIGN KEY (tenant_id, company_id) REFERENCES company (tenant_id, id),
  CONSTRAINT ck_company_policy_taxpayer CHECK (taxpayer_type IN ('general','small')),
  CONSTRAINT ck_company_policy_reservation CHECK (reservation_valid_days BETWEEN 1 AND 365 AND reservation_grace_days <= 90),
  CONSTRAINT ck_company_policy_over_receipt CHECK (over_receipt_pct BETWEEN 0 AND 10),
  CONSTRAINT ck_company_policy_flags CHECK (separate_order_approver IN (0,1) AND separate_receipt_confirmer IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='公司级业务参数（业务规则中标记为【参】的取值），修改记审计';

CREATE TABLE warehouse (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  company_id  BIGINT UNSIGNED NOT NULL COMMENT '仓库只属于一家公司（业务规则 2.1）',
  code        VARCHAR(32)  NOT NULL,
  name        VARCHAR(100) NOT NULL,
  address     VARCHAR(200) NULL,
  status      VARCHAR(16)  NOT NULL DEFAULT 'active',
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_warehouse_code (tenant_id, company_id, code),
  UNIQUE KEY uk_warehouse_scope (tenant_id, company_id, id),
  CONSTRAINT fk_warehouse_company FOREIGN KEY (tenant_id, company_id) REFERENCES company (tenant_id, id),
  CONSTRAINT ck_warehouse_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='仓库';

CREATE TABLE sys_user (
  id             BIGINT UNSIGNED NOT NULL,
  tenant_id      BIGINT UNSIGNED NOT NULL,
  username       VARCHAR(64)  NOT NULL COMMENT '登录名，租户内唯一',
  display_name   VARCHAR(64)  NOT NULL,
  password_hash  VARCHAR(255) NOT NULL COMMENT '口令摘要，算法由认证模块决定，不存明文',
  mobile         VARCHAR(32)  NULL COMMENT '敏感字段，接口按权限脱敏',
  status         VARCHAR(16)  NOT NULL DEFAULT 'active' COMMENT 'active / locked / disabled',
  last_login_at  DATETIME(3)  NULL,
  failed_login_count    SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '连续登录失败次数，登录成功后清零',
  locked_until          DATETIME(3)  NULL COMMENT '失败过多时的临时锁定到期时间（接口设计 2.2）；status = locked 表示管理员锁定',
  must_change_password  TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '管理员重置密码后为 1，下次登录须先修改',
  password_changed_at   DATETIME(3)  NULL,
  version        INT UNSIGNED NOT NULL DEFAULT 0,
  created_by     BIGINT UNSIGNED NULL,
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by     BIGINT UNSIGNED NULL,
  updated_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_user_username (tenant_id, username),
  UNIQUE KEY uk_sys_user_scope (tenant_id, id),
  CONSTRAINT fk_sys_user_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
  CONSTRAINT ck_sys_user_status CHECK (status IN ('active','locked','disabled')),
  CONSTRAINT ck_sys_user_must_change CHECK (must_change_password IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户';

CREATE TABLE sys_role (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  code        VARCHAR(64)  NOT NULL,
  name        VARCHAR(64)  NOT NULL,
  status      VARCHAR(16)  NOT NULL DEFAULT 'active',
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_role_code (tenant_id, code),
  UNIQUE KEY uk_sys_role_scope (tenant_id, id),
  CONSTRAINT fk_sys_role_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
  CONSTRAINT ck_sys_role_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='角色';

CREATE TABLE sys_permission (
  id          BIGINT UNSIGNED NOT NULL,
  code        VARCHAR(64)  NOT NULL COMMENT '权限码，例如 sales_order:approve',
  name        VARCHAR(64)  NOT NULL,
  perm_type   VARCHAR(16)  NOT NULL COMMENT 'menu 菜单 / action 操作 / field 字段可见',
  parent_id   BIGINT UNSIGNED NULL,
  sort_no     INT          NOT NULL DEFAULT 0,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_permission_code (code),
  CONSTRAINT fk_sys_permission_parent FOREIGN KEY (parent_id) REFERENCES sys_permission (id),
  CONSTRAINT ck_sys_permission_type CHECK (perm_type IN ('menu','action','field'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='权限目录，由迁移脚本维护，不分租户';

CREATE TABLE sys_user_role (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  user_id     BIGINT UNSIGNED NOT NULL,
  role_id     BIGINT UNSIGNED NOT NULL,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_user_role (tenant_id, user_id, role_id),
  CONSTRAINT fk_sys_user_role_user FOREIGN KEY (tenant_id, user_id) REFERENCES sys_user (tenant_id, id),
  CONSTRAINT fk_sys_user_role_role FOREIGN KEY (tenant_id, role_id) REFERENCES sys_role (tenant_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户角色关系';

CREATE TABLE sys_role_permission (
  id             BIGINT UNSIGNED NOT NULL,
  tenant_id      BIGINT UNSIGNED NOT NULL,
  role_id        BIGINT UNSIGNED NOT NULL,
  permission_id  BIGINT UNSIGNED NOT NULL,
  created_by     BIGINT UNSIGNED NULL,
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_role_permission (tenant_id, role_id, permission_id),
  CONSTRAINT fk_sys_role_permission_role FOREIGN KEY (tenant_id, role_id) REFERENCES sys_role (tenant_id, id),
  CONSTRAINT fk_sys_role_permission_perm FOREIGN KEY (permission_id) REFERENCES sys_permission (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='角色权限关系';

CREATE TABLE sys_user_data_scope (
  id             BIGINT UNSIGNED NOT NULL,
  tenant_id      BIGINT UNSIGNED NOT NULL,
  user_id        BIGINT UNSIGNED NOT NULL,
  scope_type     VARCHAR(16)  NOT NULL COMMENT 'company 整个公司 / warehouse 指定仓库',
  company_id     BIGINT UNSIGNED NOT NULL,
  warehouse_id   BIGINT UNSIGNED NULL,
  warehouse_key  BIGINT UNSIGNED GENERATED ALWAYS AS (IFNULL(warehouse_id, 0)) STORED COMMENT '唯一键用，NULL 记为 0',
  created_by     BIGINT UNSIGNED NULL,
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_user_data_scope (tenant_id, user_id, company_id, warehouse_key),
  CONSTRAINT fk_sys_user_data_scope_user FOREIGN KEY (tenant_id, user_id) REFERENCES sys_user (tenant_id, id),
  CONSTRAINT fk_sys_user_data_scope_company FOREIGN KEY (tenant_id, company_id) REFERENCES company (tenant_id, id),
  CONSTRAINT fk_sys_user_data_scope_wh FOREIGN KEY (tenant_id, company_id, warehouse_id) REFERENCES warehouse (tenant_id, company_id, id),
  CONSTRAINT ck_sys_user_data_scope_type CHECK (
    (scope_type = 'company' AND warehouse_id IS NULL) OR (scope_type = 'warehouse' AND warehouse_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户数据范围，查询、导出和后台任务都按此过滤';

