CREATE TABLE business_partner (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  code        VARCHAR(32)  NOT NULL,
  name        VARCHAR(100) NOT NULL,
  short_name  VARCHAR(50)  NULL,
  tax_no      VARCHAR(32)  NULL,
  status      VARCHAR(16)  NOT NULL DEFAULT 'active',
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_business_partner_code (tenant_id, code),
  UNIQUE KEY uk_business_partner_scope (tenant_id, id),
  KEY idx_business_partner_name (tenant_id, name),
  CONSTRAINT fk_business_partner_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
  CONSTRAINT ck_business_partner_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='往来单位，客户和供应商共用主体';

CREATE TABLE partner_role (
  id                   BIGINT UNSIGNED NOT NULL,
  tenant_id            BIGINT UNSIGNED NOT NULL,
  partner_id           BIGINT UNSIGNED NOT NULL,
  role                 VARCHAR(16)  NOT NULL COMMENT 'customer 客户 / supplier 供应商',
  price_tax_inclusive  TINYINT(1)   NULL COMMENT '新单据默认价格口径，NULL 表示未设置，按含税处理（R3-01）',
  status               VARCHAR(16)  NOT NULL DEFAULT 'active',
  version              INT UNSIGNED NOT NULL DEFAULT 0,
  created_by           BIGINT UNSIGNED NULL,
  created_at           DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by           BIGINT UNSIGNED NULL,
  updated_at           DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_partner_role (tenant_id, partner_id, role),
  CONSTRAINT fk_partner_role_partner FOREIGN KEY (tenant_id, partner_id) REFERENCES business_partner (tenant_id, id),
  CONSTRAINT ck_partner_role_role CHECK (role IN ('customer','supplier')),
  CONSTRAINT ck_partner_role_tax CHECK (price_tax_inclusive IS NULL OR price_tax_inclusive IN (0,1)),
  CONSTRAINT ck_partner_role_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='往来单位角色及角色专属设置';

CREATE TABLE partner_contact (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  partner_id  BIGINT UNSIGNED NOT NULL,
  name        VARCHAR(50)  NOT NULL,
  mobile      VARCHAR(32)  NULL COMMENT '敏感字段，需“查看客户联系方式”权限',
  email       VARCHAR(100) NULL,
  address     VARCHAR(200) NULL,
  is_default  TINYINT(1)   NOT NULL DEFAULT 0,
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_partner_contact_partner (tenant_id, partner_id),
  CONSTRAINT fk_partner_contact_partner FOREIGN KEY (tenant_id, partner_id) REFERENCES business_partner (tenant_id, id),
  CONSTRAINT ck_partner_contact_default CHECK (is_default IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='往来单位联系人';

CREATE TABLE cash_account (
  id            BIGINT UNSIGNED NOT NULL,
  tenant_id     BIGINT UNSIGNED NOT NULL,
  company_id    BIGINT UNSIGNED NOT NULL,
  code          VARCHAR(32)  NOT NULL,
  name          VARCHAR(100) NOT NULL,
  account_type  VARCHAR(16)  NOT NULL COMMENT 'cash 现金 / bank 银行 / other 其他',
  currency      CHAR(3)      NOT NULL DEFAULT 'CNY',
  bank_name     VARCHAR(100) NULL,
  account_no    VARCHAR(64)  NULL COMMENT '银行账号，敏感字段，接口按权限脱敏',
  status        VARCHAR(16)  NOT NULL DEFAULT 'active',
  version       INT UNSIGNED NOT NULL DEFAULT 0,
  created_by    BIGINT UNSIGNED NULL,
  created_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by    BIGINT UNSIGNED NULL,
  updated_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_cash_account_code (tenant_id, company_id, code),
  UNIQUE KEY uk_cash_account_scope (tenant_id, company_id, id),
  UNIQUE KEY uk_cash_account_currency (tenant_id, company_id, currency, id),
  CONSTRAINT fk_cash_account_company FOREIGN KEY (tenant_id, company_id) REFERENCES company (tenant_id, id),
  CONSTRAINT ck_cash_account_type CHECK (account_type IN ('cash','bank','other')),
  CONSTRAINT ck_cash_account_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='结算账户';

CREATE TABLE cash_account_balance (
  id               BIGINT UNSIGNED NOT NULL,
  tenant_id        BIGINT UNSIGNED NOT NULL,
  company_id       BIGINT UNSIGNED NOT NULL,
  cash_account_id  BIGINT UNSIGNED NOT NULL,
  balance          DECIMAL(24,2) NOT NULL DEFAULT 0 COMMENT '已确认资金余额，与账本分录同事务更新',
  version          INT UNSIGNED NOT NULL DEFAULT 0,
  created_at       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_cash_account_balance (tenant_id, company_id, cash_account_id),
  CONSTRAINT fk_cash_account_balance_account FOREIGN KEY (tenant_id, company_id, cash_account_id) REFERENCES cash_account (tenant_id, company_id, id),
  CONSTRAINT ck_cash_account_balance_nonneg CHECK (balance >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='结算账户余额投影，余额不能为负（R4-10）';

