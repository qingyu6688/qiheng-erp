  UNIQUE KEY uk_import_job_scope (tenant_id, company_id, id),
  KEY idx_import_job_status (status, created_at),
  CONSTRAINT fk_import_job_company FOREIGN KEY (tenant_id, company_id) REFERENCES company (tenant_id, id),
  CONSTRAINT fk_import_job_attachment FOREIGN KEY (attachment_id) REFERENCES attachment (id),
  CONSTRAINT ck_import_job_status CHECK (status IN ('pending','running','succeeded','failed','partial')),
  CONSTRAINT ck_import_job_rows CHECK (success_rows + failed_rows <= total_rows)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='导入任务';

