  CONSTRAINT ck_unit_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='计量单位';

CREATE TABLE product_category (
  id          BIGINT UNSIGNED NOT NULL,
  tenant_id   BIGINT UNSIGNED NOT NULL,
  parent_id   BIGINT UNSIGNED NULL,
  code        VARCHAR(32)  NOT NULL,
  name        VARCHAR(64)  NOT NULL,
  path        VARCHAR(255) NOT NULL COMMENT '祖先路径，如 /1/5/，用于按分类子树查询',
  sort_no     INT          NOT NULL DEFAULT 0,
  status      VARCHAR(16)  NOT NULL DEFAULT 'active',
  version     INT UNSIGNED NOT NULL DEFAULT 0,
  created_by  BIGINT UNSIGNED NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by  BIGINT UNSIGNED NULL,
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_category_code (tenant_id, code),
  UNIQUE KEY uk_product_category_scope (tenant_id, id),
  KEY idx_product_category_path (tenant_id, path),
  CONSTRAINT fk_product_category_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
  CONSTRAINT fk_product_category_parent FOREIGN KEY (tenant_id, parent_id) REFERENCES product_category (tenant_id, id),
  CONSTRAINT ck_product_category_status CHECK (status IN ('active','disabled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商品分类';

CREATE TABLE product (
  id            BIGINT UNSIGNED NOT NULL,
  tenant_id     BIGINT UNSIGNED NOT NULL,
  category_id   BIGINT UNSIGNED NOT NULL,
  code          VARCHAR(32)  NOT NULL COMMENT 'SPU 编码',
  name          VARCHAR(100) NOT NULL,
  item_type     VARCHAR(16)  NOT NULL DEFAULT 'goods' COMMENT 'goods 商品 / material 物料 / finished 成品，后两类为生产预留',
  base_unit_id  BIGINT UNSIGNED NOT NULL COMMENT '基础单位，库存数量都按它记录（业务规则 2.2）',
  status        VARCHAR(16)  NOT NULL DEFAULT 'active',
  version       INT UNSIGNED NOT NULL DEFAULT 0,
