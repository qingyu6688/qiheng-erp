CREATE TABLE mfg_issue_doc (
    id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    document_no VARCHAR(64) NOT NULL,
    work_order_id BIGINT UNSIGNED NOT NULL,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    business_date DATE NOT NULL,
    period_id BIGINT UNSIGNED NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'draft',
    owner_user_id BIGINT UNSIGNED NOT NULL,
    owner_department_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
    remark VARCHAR(500) NULL,
    submitted_by BIGINT UNSIGNED NULL,
    approved_by BIGINT UNSIGNED NULL,
    approved_at DATETIME(3) NULL,
    posted_by BIGINT UNSIGNED NULL,
    posted_at DATETIME(3) NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    direction VARCHAR(6) NOT NULL,
    over_issue TINYINT(1) NOT NULL DEFAULT 0,
    wf_instance_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY(id),
    UNIQUE KEY uk_mfg_issue_scope(tenant_id,company_id,id),
    UNIQUE KEY uk_mfg_issue_no(tenant_id,company_id,document_no),
    KEY idx_mfg_issue_order(tenant_id,company_id,work_order_id,status,id),
    KEY idx_mfg_issue_period(tenant_id,company_id,period_id,status,work_order_id),
    KEY idx_mfg_issue_warehouse(tenant_id,company_id,warehouse_id,status,id),
    CONSTRAINT fk_mfg_issue_order FOREIGN KEY(tenant_id,company_id,work_order_id) REFERENCES mfg_work_order(tenant_id,company_id,id),
    CONSTRAINT fk_mfg_issue_warehouse FOREIGN KEY(tenant_id,company_id,warehouse_id) REFERENCES warehouse(tenant_id,company_id,id),
    CONSTRAINT fk_mfg_issue_period FOREIGN KEY(tenant_id,company_id,period_id) REFERENCES accounting_period(tenant_id,company_id,id),
    CONSTRAINT ck_mfg_issue_direction CHECK(direction IN ('issue','return') AND over_issue IN (0,1)),
    CONSTRAINT ck_mfg_issue_status CHECK(status IN ('draft','pending','approved','rejected','posted','reversed','cancelled')),
    CONSTRAINT ck_mfg_issue_approval CHECK(approved_by IS NULL OR (approved_by<>created_by AND approved_by<>submitted_by)),
    CONSTRAINT ck_mfg_issue_posted CHECK((status IN ('posted','reversed'))=(period_id IS NOT NULL AND posted_at IS NOT NULL))
);

CREATE TABLE mfg_issue_line (
    id BIGINT UNSIGNED NOT NULL,
    tenant_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    doc_id BIGINT UNSIGNED NOT NULL,
    line_no INT UNSIGNED NOT NULL,
    sku_id BIGINT UNSIGNED NOT NULL,
    unit_id BIGINT UNSIGNED NOT NULL,
    qty DECIMAL(24,6) NOT NULL,
    material_id BIGINT UNSIGNED NOT NULL,
    material_qty DECIMAL(24,6) NOT NULL,
    original_issue_line_id BIGINT UNSIGNED NULL,
    unit_cost DECIMAL(24,8) NULL,
    amount DECIMAL(24,2) NULL,
    batch_id BIGINT UNSIGNED NULL,
    location_key VARCHAR(64) NOT NULL DEFAULT '',
    stock_selection JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY(id),
    UNIQUE KEY uk_mfg_issue_line_scope(tenant_id,company_id,id),
    UNIQUE KEY uk_mfg_issue_line_number(tenant_id,company_id,doc_id,line_no),
    KEY idx_mfg_issue_return(tenant_id,company_id,original_issue_line_id,doc_id),
    CONSTRAINT fk_mfg_issue_line_doc FOREIGN KEY(tenant_id,company_id,doc_id) REFERENCES mfg_issue_doc(tenant_id,company_id,id),
    CONSTRAINT fk_mfg_issue_line_sku FOREIGN KEY(tenant_id,sku_id) REFERENCES sku(tenant_id,id),
    CONSTRAINT fk_mfg_issue_line_unit FOREIGN KEY(tenant_id,unit_id) REFERENCES unit(tenant_id,id),
    CONSTRAINT fk_mfg_issue_line_batch FOREIGN KEY(tenant_id,company_id,batch_id) REFERENCES inv_batch(tenant_id,company_id,id),
    CONSTRAINT fk_mfg_issue_line_material FOREIGN KEY(tenant_id,company_id,material_id) REFERENCES mfg_work_order_material(tenant_id,company_id,id),
    CONSTRAINT fk_mfg_issue_line_original FOREIGN KEY(tenant_id,company_id,original_issue_line_id) REFERENCES mfg_issue_line(tenant_id,company_id,id),
    CONSTRAINT ck_mfg_issue_line_qty CHECK(qty>0 AND material_qty>0),
    CONSTRAINT ck_mfg_issue_line_amount CHECK(amount IS NULL OR amount>=0)
);

