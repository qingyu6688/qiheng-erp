import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { env } from 'node:process'

async function verifyWorkspaceNavigation(page: Page, testInfo: TestInfo): Promise<void> {
  await expect(page.locator('[data-trade="sales"]')).toBeVisible()
  await expect(page.locator('[data-trade="purchase"]')).toBeVisible()
  await expect(page.getByRole('img', { name: '近十二个月销售确认金额与采购收货金额折线图' })).toBeVisible()
  const todos = page.getByRole('region', { name: '待办', exact: true })
  await expect(todos.getByRole('button', { name: /^全部/ })).toBeVisible()
  const shortcuts = page.getByRole('region', { name: '快捷入口' })
  await expect(shortcuts.getByRole('link')).toHaveCount(8)
  await shortcuts.getByRole('button', { name: '配置' }).click()
  const preferences = page.getByRole('dialog', { name: '配置快捷入口' })
  await preferences.getByText('新建采购订单', { exact: true }).click()
  await expect(preferences.getByRole('checkbox', { name: '新建采购订单' })).not.toBeChecked()
  await preferences.getByRole('button', { name: '保存', exact: true }).click()
  await expect(shortcuts.getByRole('link', { name: '新建采购订单' })).toHaveCount(0)
  await page.reload()
  await expect(shortcuts.getByRole('link')).toHaveCount(7)
  const account = page.locator('.account-menu > summary')
  await account.click()
  const density = page.getByLabel('界面密度')
  await density.selectOption('compact')
  await expect(page.locator('html')).toHaveAttribute('data-density', 'compact')
  await density.selectOption('default')
  await account.click()
  await page.screenshot({
    path: testInfo.outputPath('art-workbench.png'),
    fullPage: true,
    animations: 'disabled',
  })

  await todos.getByRole('button', { name: /^待审核销售订单/ }).click()
  await todos.getByRole('link', { name: '查看全部待审核销售订单' }).click()
  await expect(page).toHaveURL(/sales-orders\?status=pending/)
  const tabs = page.getByRole('navigation', { name: '工作标签' })
  await tabs.getByRole('link', { name: '切换到工作台' }).click()
  await tabs.getByRole('link', { name: '切换到销售订单' }).click()
  await expect(page).toHaveURL(/sales-orders\?status=pending/)
  await tabs.getByRole('link', { name: '切换到销售订单' }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '固定', exact: true }).click()
  await expect(tabs.getByLabel('已固定')).toBeVisible()
  await tabs.getByRole('button', { name: '关闭销售订单标签' }).click()
  await expect(page.getByRole('heading', { name: '工作台', exact: true })).toBeVisible()
  await expect(page.getByRole('complementary', { name: '公告与最近访问' }).getByRole('link', { name: '销售订单', exact: true })).toBeVisible()
  await expect(tabs.getByRole('link', { name: '切换到销售订单' })).toHaveCount(0)

  const desktop = page.viewportSize()!
  await page.keyboard.press('Control+k')
  const search = page.getByRole('dialog', { name: '全局搜索' })
  await search.getByRole('textbox', { name: '菜单、单号、客户或商品' }).fill('销售订单')
  await expect(search.getByRole('link', { name: /^销售订单/ })).toBeVisible()
  await expect(search.getByRole('link', { name: /^库存盘点/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(search).toBeHidden()
  await page.setViewportSize({ width: 1024, height: 768 })
  const inventory = page.getByRole('button', { name: '库存', exact: true })
  await inventory.press('Enter')
  const inventoryLink = page.getByRole('link', { name: '实时库存', exact: true })
  await expect(inventoryLink).toBeFocused()
  await expect(page.getByRole('heading', { name: '工作台', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  const open = page.getByRole('button', { name: '展开导航' })
  await open.click()
  const menu = page.getByRole('dialog', { name: '业务导航' })
  await expect(menu).toBeVisible()
  await expect(menu.getByText('柒衡 ERP', { exact: true })).toBeVisible()
  await expect(menu.getByRole('button', { name: '关闭导航' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(open).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: testInfo.outputPath('art-workbench-mobile.png'), fullPage: true })
  await open.click()
  await menu.getByRole('button', { name: '库存', exact: true }).click()
  await menu.getByRole('link', { name: '实时库存', exact: true }).click()
  await expect(menu).toBeHidden()
  await expect(page.getByRole('heading', { name: '实时库存', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({
    path: testInfo.outputPath('art-inventory-mobile.png'),
    fullPage: true,
    animations: 'disabled',
  })
  await page.setViewportSize(desktop)
}

test('工作台入口、单据筛选刷新、独立订单50行与未保存保护', async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  if (!env.ERP_E2E_PASSWORD || !/^E2E-[a-f0-9]{12}$/.test(env.ERP_E2E_TENANT_CODE ?? ''))
    throw new Error('UI 验收须使用随机测试企业与临时口令')
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/login')
  await expect(page).toHaveTitle('柒衡 ERP')
  await expect(page.locator('.login-brand').getByText('柒衡 ERP', { exact: true })).toBeVisible()
  await page.getByLabel('企业编码').fill(env.ERP_E2E_TENANT_CODE!)
  await page.getByLabel('用户名').fill('admin')
  await page.locator('#password').fill(env.ERP_E2E_PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台', exact: true })).toBeVisible()
  await expect(page).toHaveTitle('柒衡 ERP')
  await expect(page.locator('#workspace-sidebar').getByText('柒衡 ERP', { exact: true })).toBeVisible()
  await verifyWorkspaceNavigation(page, testInfo)
  await page.goto('/sales-orders?status=approved&dateFrom=2026-11-01&dateTo=2026-11-15')
  await expect(page.getByRole('tab', { name: /^已批准/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#sales-orders-from')).toHaveValue('2026-11-01')
  await expect(page.locator('#sales-orders-to')).toHaveValue('2026-11-15')
  await page.reload()
  await expect(page.locator('#sales-orders-from')).toHaveValue('2026-11-01')
  await expect(page.getByRole('tab', { name: /^已批准/ })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: /^全部/ }).click()
  await expect(page).toHaveURL(/status=/)
  await page.screenshot({ path: testInfo.outputPath('document-list-design.png'), fullPage: true })
  await page.getByRole('button', { name: '新建销售订单', exact: true }).click()
  await expect(page).toHaveURL(/\/sales-orders\/new$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.order-editor-page')).toBeVisible()
  await expect(page.getByRole('button', { name: '添加商品行', exact: true })).toBeEnabled()
  for (let index = 1; index < 50; index++)
    await page.getByRole('button', { name: '添加商品行', exact: true }).click()
  await expect(page.locator('.sales-input-table tbody tr')).toHaveCount(50)
  await expect(page.locator('.order-editor-footer')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('order-editor-50-lines.png'), fullPage: true })
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page).toHaveURL(/\/sales-orders\/new$/)
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page).toHaveURL(/\/sales-orders$/)
  await page.goto('/inventory-balances')
  await page
    .locator('label.el-checkbox')
    .filter({ has: page.getByLabel('隐藏零库存', { exact: true }) })
    .click()
  await expect(page.getByLabel('隐藏零库存', { exact: true })).toBeChecked()
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page).toHaveURL(/hideZero=true/)
  await page.reload()
  await expect(page.getByLabel('隐藏零库存', { exact: true })).toBeChecked()
  await expect(page.getByRole('region', { name: '实时库存列表' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('inventory-design.png'), fullPage: true })
  expect(errors).toEqual([])
})
